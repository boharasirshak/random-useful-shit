// out/popular.json → the app: src/tools/calories/data/catalog.ts (the JSON as a string), assets/menu/catalog/<id>.jpg
// and data/catalogImages.ts (the require() map Metro needs). Run after build.mjs. The full set stays in out/ for publish.sh.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib.mjs';

const APP = join(ROOT, '..', '..', 'apps', 'mobile');
const DATA = join(APP, 'src', 'tools', 'calories', 'data');
const IMG = join(APP, 'assets', 'menu', 'catalog');
const popular = JSON.parse(readFileSync(join(ROOT, 'out', 'popular.json'), 'utf8'));

if (existsSync(IMG)) rmSync(IMG, { recursive: true });
mkdirSync(IMG, { recursive: true });
const items = popular.items.map(i => {
  const { src, pop, ...o } = i; // the app doesn't need the source URL or scan count
  if (o.image) {
    const from = join(ROOT, 'out', o.image);
    if (existsSync(from)) copyFileSync(from, join(IMG, `${o.id}.jpg`));
    else delete o.image;
  }
  return o;
});
const catalog = { version: popular.version, places: popular.places, items };
writeFileSync(join(DATA, 'catalog.ts'), `// Generated by packages/food-data/export.mjs (version ${popular.version}). Do not edit: re-run the export.\n// JSON as a string: Metro and Node both parse it without import attributes, and tsc doesn't type-check a megabyte literal.\nexport const CATALOG_JSON = ${JSON.stringify(JSON.stringify(catalog))};\n`);
const files = readdirSync(IMG).sort();
writeFileSync(join(DATA, 'catalogImages.ts'), `// Generated by packages/food-data/export.mjs. Photos for the bundled catalog, keyed by item id. Do not edit.\nexport const CATALOG_IMAGES: Record<string, number> = {\n${files.map(f => `  '${f.slice(0, -4)}': require('../../../../assets/menu/catalog/${f}'),`).join('\n')}\n};\n`);
const mb = n => (n / 1e6).toFixed(1) + ' MB';
let bytes = 0;
for (const f of files) bytes += readFileSync(join(IMG, f)).length;
console.log(`catalog.ts: ${items.length} items, ${popular.places.length} places, ${mb(readFileSync(join(DATA, 'catalog.ts')).length)}; ${files.length} photos, ${mb(bytes)}`);
